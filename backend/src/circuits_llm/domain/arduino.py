"""Arduino pin behaviours: validation helpers and the generated sketch.

The LLM never writes C++. It programs pins with a few declarative behaviours
(high, low, blink, pwm, rule); the simulator drives the pins from the same
behaviours and :func:`sketch` turns them into an ``.ino`` file, so the code a user
flashes does exactly what was simulated.
"""

from __future__ import annotations

from typing import Final

from .catalog import ARDUINO_ANALOG_PINS
from .circuit import Component, PinBehavior
from .expectations import ExpectationSyntaxError, Signal, parse_condition

DEFAULT_PWM_HZ: Final = 490.0  # analogWrite() on most Uno pins
ARDUINO_LOGIC_V: Final = 5.0
_ADC_STEPS: Final = 1023


def rule_condition(behavior: PinBehavior) -> tuple[Signal, str, float]:
    """(input pin signal, operator, threshold volts) of a ``rule`` behaviour."""
    if behavior.when is None:
        raise ExpectationSyntaxError("a 'rule' needs 'when', e.g. 'A0 < 2.5'")
    signal, comparison = parse_condition(behavior.when, frozenset())
    if signal.kind != "voltage" or signal.target.upper() not in ARDUINO_ANALOG_PINS:
        raise ExpectationSyntaxError(
            f"'when' must compare an analog input A0-A5 with a voltage, e.g. 'A0 < 2.5', "
            f"not '{behavior.when}'"
        )
    return Signal("voltage", signal.target.upper()), comparison.operator, comparison.value


def _pin_number(pin: str) -> str:
    return pin[1:]  # "D13" -> "13"


def _seconds_to_ms(seconds: float) -> int:
    return max(1, round(seconds * 1000))


def sketch(component: Component) -> str:
    """The ``.ino`` source for an Arduino component's behaviours."""
    behaviors = component.behavior or []
    setup = [f"  pinMode({_pin_number(b.pin)}, OUTPUT);" for b in behaviors]
    loop: list[str] = []
    for b in behaviors:
        pin = _pin_number(b.pin)
        match b.output:
            case "high" | "low":
                setup.append(f"  digitalWrite({pin}, {b.output.upper()});")
            case "pwm":
                duty = b.duty if b.duty is not None else 0.5
                level = round(duty * 255)
                note = ""
                if b.frequency is not None and abs(b.frequency - DEFAULT_PWM_HZ) > 1:
                    note = f"  // simulated at {b.frequency:g} Hz; analogWrite() runs at ~490 Hz"
                setup.append(f"  analogWrite({pin}, {level});  // {duty:.0%} duty{note}")
            case "blink":
                period_ms = _seconds_to_ms(b.period or 1.0)
                on_ms = _seconds_to_ms((b.period or 1.0) * (b.duty if b.duty is not None else 0.5))
                loop.append(f"  // {b.pin}: blink, {period_ms} ms period, {on_ms} ms on")
                loop.append(f"  digitalWrite({pin}, (now % {period_ms}) < {on_ms} ? HIGH : LOW);")
            case "rule":
                signal, operator, threshold = rule_condition(b)
                volts = f"analogRead({signal.target}) * (5.0 / {_ADC_STEPS}.0)"
                loop.append(f"  // {b.pin}: HIGH while {signal.target} {operator} {threshold:g} V")
                loop.append(
                    f"  digitalWrite({pin}, {volts} {operator} {threshold:g} ? HIGH : LOW);"
                )
    header = [
        f"// {component.id}: generated by circuits-llm from the simulated pin behaviours.",
        "// Upload with the Arduino IDE (board: Arduino Uno).",
        "",
        "void setup() {",
        *setup,
        "}",
        "",
        "void loop() {",
    ]
    body = (
        ["  unsigned long now = millis();", *loop] if any("now" in line for line in loop) else loop
    )
    return "\n".join([*header, *body, "}", ""])
